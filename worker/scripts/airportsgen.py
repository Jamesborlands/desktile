#!/usr/bin/env python3
# Builds src/airports.ts: IATA code -> city and position for every airport with scheduled
# service (OurAirports, public domain). The Flightradar24 route lookup only gives IATA codes.
#   python3 scripts/airportsgen.py
import csv
import io
import os
import urllib.request

URL = "https://davidmegginson.github.io/ourairports-data/airports.csv"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "airports.ts")

rows = csv.DictReader(io.TextIOWrapper(urllib.request.urlopen(URL), encoding="utf-8"))
lines = []
for r in rows:
    if r["scheduled_service"] != "yes" or len(r["iata_code"]) != 3:
        continue
    city = (r["municipality"] or r["name"]).replace("|", " ").strip()
    lines.append(f'{r["iata_code"]}|{city}|{float(r["latitude_deg"]):.3f}|{float(r["longitude_deg"]):.3f}')
lines.sort()

with open(OUT, "w") as f:
    f.write("// Generated by scripts/airportsgen.py from OurAirports (public domain). Do not edit.\n")
    f.write("// IATA|city|lat|lon, one airport per line.\n")
    f.write("export const AIRPORTS = `\n" + "\n".join(lines) + "\n`;\n")
print(f"{len(lines)} airports -> {OUT}")
