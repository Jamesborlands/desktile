# Build src/hotspots.h: the hotspot list plus Natural Earth 10m coastline and land
# borders clipped around each one. San Diego (hotspot 0) uses the finer OSM coastline
# in mapdata.h instead.
#   python3 tools/hotspotgen.py ne_10m_coastline.geojson ne_10m_admin_0_boundary_lines_land.geojson src/hotspots.h
# Ship hotspot ids must match REGIONS in worker/src/ships.ts.
import json, sys, math

coast, border, out = sys.argv[1:4]

# id, label, lat, lon, planes range nm, ships range nm, planes filter (0 all, 1 military),
# screens (1 = Planes, 2 = Ships, 3 = both). Planes visits airports, Ships visits waterways.
HOTSPOTS = [
    ("sandiego",   "SAN DIEGO",        32.95, -117.25,  25,  50, 0, 3),
    ("lax",        "LOS ANGELES",      33.94, -118.41,  30,  30, 0, 1),
    ("denver",     "DENVER",           39.86, -104.67,  30,  30, 0, 1),
    ("london",     "LONDON HEATHROW",  51.47,    -0.45,  30,  30, 0, 1),
    ("tokyo",      "TOKYO",            35.65,   140.05,  40,  40, 0, 1),
    ("hormuz",     "STRAIT OF HORMUZ", 26.35,    56.45,   60,  50, 1, 2),
    ("gulf",       "PERSIAN GULF",     26.5,     52.0,   200, 200, 1, 2),
    ("dover",      "DOVER STRAIT",     51.0,      1.45,   40,  35, 0, 2),
    ("rotterdam",  "ROTTERDAM",        51.95,     4.0,    30,  20, 0, 2),
    ("singapore",  "SINGAPORE STRAIT",  1.25,   103.9,    40,  30, 0, 2),
    ("hongkong",   "HONG KONG",        22.3,    114.1,    30,  25, 0, 2),
    ("taiwan",     "TAIWAN STRAIT",    24.4,    119.6,   120, 100, 0, 2),
    ("tokyobay",   "TOKYO BAY",        35.4,    139.8,    35,  30, 0, 2),
    ("pugetsound", "PUGET SOUND",      47.8,   -122.5,    40,  35, 0, 2),
    ("sfbay",      "SF BAY",           37.8,   -122.4,    30,  25, 0, 2),
    ("nyc",        "NEW YORK HARBOR",  40.6,    -74.0,    30,  25, 0, 2),
]

def box(lat, lon, nm):
    dlat = nm / 60
    dlon = nm / (60 * math.cos(math.radians(lat)))
    return (lat - dlat, lat + dlat, lon - dlon, lon + dlon)

def rdp(pts, tol):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]
    dx, dy = b[0] - a[0], b[1] - a[1]
    n = math.hypot(dx, dy) or 1e-12
    dmax, idx = 0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * (pts[i][0] - a[0]) - dx * (pts[i][1] - a[1])) / n
        if d > dmax: dmax, idx = d, i
    if dmax > tol: return rdp(pts[:idx + 1], tol)[:-1] + rdp(pts[idx:], tol)
    return [a, b]

def parts(path):
    for f in json.load(open(path))['features']:
        g = f['geometry']
        if not g: continue
        yield from (g['coordinates'] if g['type'] == 'MultiLineString' else [g['coordinates']])

def clip(part, bx):
    inside = lambda p: bx[0] <= p[1] <= bx[1] and bx[2] <= p[0] <= bx[3]
    run = []
    for i, p in enumerate(part):
        if inside(p) or (i + 1 < len(part) and inside(part[i + 1])) or (run and inside(part[i - 1])):
            run.append(p)
        elif run:
            yield run; run = []
    if len(run) > 1: yield run

data = {'coast': list(parts(coast)), 'border': list(parts(border))}
polys = []  # (kind, points)
for hid, label, lat, lon, rp, rs, flt, scr in HOTSPOTS[1:]:
    reach = (rp if scr == 1 else rs if scr == 2 else max(rp, rs)) * 1.8  # room to pan a bit past the corners
    bx = box(lat, lon, reach)
    tol = max(0.002, reach / 60 * 0.003)  # degrees; coarser for wide views
    for kind in ('coast', 'border'):
        for part in data[kind]:
            for run in clip(part, bx):
                if len(run) > 3 and run[0] == run[-1]:
                    m = len(run) // 2
                    s = rdp(run[:m + 1], tol)[:-1] + rdp(run[m:], tol)
                else:
                    s = rdp(run, tol)
                if len(s) > 1: polys.append((kind, s))

with open(out, 'w') as f:
    f.write('// Hotspots and their coastlines (Natural Earth 10m, public domain). Generated by hotspotgen.py. Do not edit.\n')
    f.write('#pragma once\n#include <stdint.h>\n\n')
    f.write('struct Hotspot { const char *id, *label; float lat, lon; float range[2]; uint8_t filter, screens; };\n')
    f.write('// range: default map range (nm) for planes, ships. filter: planes filter on arrival.\n')
    f.write('// screens: 1 = on the Planes list, 2 = on the Ships list.\n')
    f.write('static const Hotspot HOTSPOTS[] = {\n')
    for hid, label, lat, lon, rp, rs, flt, scr in HOTSPOTS:
        f.write('  {"%s", "%s", %.4ff, %.4ff, {%d, %d}, %d, %d},\n' % (hid, label, lat, lon, rp, rs, flt, scr))
    f.write('};\nstatic const int HOTSPOT_COUNT = %d;\n\n' % len(HOTSPOTS))
    f.write('// Points are (lat, lon) in 1e-4 degree units.\n')
    f.write('static const int32_t HS_PTS[][2] = {\n')
    starts, total = [], 0
    for kind, s in polys:
        starts.append((total, len(s), 1 if kind == 'border' else 0))
        f.write('  ' + ', '.join('{%d, %d}' % (round(la * 1e4), round(lo * 1e4)) for lo, la in s) + ',\n')
        total += len(s)
    f.write('};\n\nstatic const MapLine HS_LINES[] = {\n')
    for st, c, b in starts: f.write('  {%d, %d, %d},\n' % (st, c, b))
    f.write('};\nstatic const int HS_LINE_COUNT = %d;\n' % len(starts))
print(len(polys), 'lines,', sum(len(s) for _, s in polys), 'points')
