# Build LVGL 9 ARGB8888 images from rendered PNGs: icons2c.py out.h NAME=png:WxH[:flip] ...
# Each icon is fitted inside WxH, desaturated to grey, and optionally mirrored.
import sys
from PIL import Image, ImageOps
out = sys.argv[1]
with open(out, 'w') as f:
    f.write('// Map icons generated by tools/icons2c.py from design/icons/*.svg. Do not edit.\n#pragma once\n#include <lvgl.h>\n\n')
    for spec in sys.argv[2:]:
        name, rest = spec.split('=')
        parts = rest.split(':')
        src, box = parts[0], parts[1]
        BW, BH = map(int, box.split('x'))
        im = Image.open(src).convert('RGBA')
        im = im.crop(im.getchannel('A').getbbox())
        if 'flip' in parts[2:]: im = ImageOps.mirror(im)
        k = min(BW / im.width, BH / im.height)
        W, H = max(1, round(im.width * k)), max(1, round(im.height * k))
        im = im.resize((W, H), Image.LANCZOS)
        a = im.getchannel('A')
        im = Image.merge('RGBA', (*[im.convert('L')] * 3, a))  # pure greys, like the rest
        px = im.load()
        data = []
        for y in range(H):
            for x in range(W):
                r, g, b, a = px[x, y]
                data += [b, g, r, a]  # LVGL ARGB8888 is stored B, G, R, A
        f.write('static const uint8_t %s_PX[] = {\n' % name)
        for i in range(0, len(data), 16):
            f.write('  ' + ', '.join('0x%02x' % v for v in data[i:i + 16]) + ',\n')
        f.write('};\n')
        f.write('static const lv_image_dsc_t %s_IMG = {\n' % name)
        f.write('    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, .flags = 0, .w = %d, .h = %d, .stride = %d, .reserved_2 = 0},\n' % (W, H, W * 4))
        f.write('    .data_size = sizeof(%s_PX),\n    .data = %s_PX,\n    .reserved = NULL,\n};\n\n' % (name, name))
        print(name, W, 'x', H)
